"""
Receiver jamming defense (idea from Zheng et al., IEEE TSP 2013).

The defense itself is in Classes/JammingChannel.py: it calculates the chance
that a packet gets through to Bob and to Eve when Bob jams. Jamming lowers
Eve's chance a lot, and Bob's only a little (the part of his own jamming he
cannot cancel). This file tests it for several jamming strengths.

Everything else is Albin's baseline: Alice sends every state, Bob uses the HMM
decoder, Eve is the random forest. Eve is trained with the same jamming, so she
knows about the defense.

"""
from pathlib import Path

import numpy as np

from Classes.MarkovChain import MarkovChain #each true message is generated by a Markov chain with 4 states and the transition matrix P
from Classes.Channel import JammingChannel #something that can create a channel with packet loss
from Classes.Decoder import HMMDecoder #bobs brain, he uses the HMM decoder to guess the true state from the received packet
from Classes.Sender import Sender #alice's brain, she sends the true state with probability
from Classes.EveLearner import RandomForestEve 
from Classes.TrainEve import RandomForestTrainer #eves brain, she uses a random forest to guess the true state from the received packet
from Classes.SimulationOptions import simulation_options
import time

start = time.perf_counter()

#############################################
########### Tweak variables here: ###########
#############################################
PRETRAINED_MODEL = None #Set to None if we want to train new, otherwise the filename if we want to use a previous trained
#PRETRAINED_MODEL = "eve_random_forest.joblib"

# Ignore these if using pretrained model:
DEFENSE = "alma"
MODEL_NAME = f"eve_{DEFENSE}.joblib"
TRAINING_RUNS = 5
T_PER_RUN = 2000

SENDING_PROBABILITY = 1.0
BOB_RECEPTION_PROBABILITY = 0.99
EVE_RECEPTION_PROBABILITY = 0.50
T = 100_000

JAM_POWERS = [0, 1, 3, 10, 42]  # how strong Bob's jamming is (0 = no jamming)
SELF_INTERFERENCE = 0.1         # share of Bob's jamming he can NOT cancel (0 = perfect)

states = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1],
])

# Transition matrix for the Markov chain that generates the true states
P = np.array([
    [0.60, 0.10, 0.10, 0.20],
    [0.25, 0.35, 0.15, 0.25],
    [0.25, 0.15, 0.35, 0.25],
    [0.20, 0.10, 0.10, 0.60],
])

options = simulation_options(DEFENSE, T, TRAINING_RUNS, T_PER_RUN)
T = options.steps
TRAINING_RUNS = options.training_runs
T_PER_RUN = options.training_steps
model_path = options.model_dir / MODEL_NAME
if options.model is not None:
    PRETRAINED_MODEL = options.model



#defines experiment, but does not run it yet.
#Separate function to test all different jamming powers quickly.
def run(jam_power):
    source_rng = np.random.default_rng(42)
    sender_rng = np.random.default_rng(43)
    bob_rng = np.random.default_rng(44)
    eve_rng = np.random.default_rng(45)

    chain = MarkovChain(states=states, transition_matrix=P, rng=source_rng)

    sender = Sender(
        sending_probability=SENDING_PROBABILITY,
        rng=sender_rng
    )

    bob_decoder = HMMDecoder(states=states, transition_matrix=P)
    
    # 1. Calculate the chances and make the two channels
    bob_channel = JammingChannel(
        reception_probability=BOB_RECEPTION_PROBABILITY,
        jam_power=SELF_INTERFERENCE * jam_power, #Bob: loud Alice, but he hears some of his own jamming.
        rng=bob_rng
    )

    eve_channel = JammingChannel(
        reception_probability=EVE_RECEPTION_PROBABILITY,
        jam_power= jam_power, #Eve: quieter Alice, but she hears all of Bob's jamming.
        rng=eve_rng
    )

    # 2. Train Eve on traffic with the same jamming
    if PRETRAINED_MODEL is None:
        training_sender = Sender(
            sending_probability=SENDING_PROBABILITY,
            rng=np.random.default_rng(1337)
        )

        eve_trainer = RandomForestTrainer(
            model_path=model_path,
            defense=DEFENSE,
            states=states,
            P=P,
            training_runs=TRAINING_RUNS,
            T_per_run=T_PER_RUN,
            eve_reception_probability=(1-eve_channel.get_packet_loss()),
            bob_reception_probability=(1-bob_channel.get_packet_loss()),
            sender=training_sender,
        )

        eve_trainer.train()
        eve_decoder = RandomForestEve(
            model_path=model_path, defense=DEFENSE
        )

    else:
        eve_decoder = RandomForestEve(
            model_path=options.model_dir / PRETRAINED_MODEL, defense=DEFENSE
        )

    if options.train_only:
        raise SystemExit(0)

    state_history = chain.sample(T=T, start_state=0)

    bob_prediction_S = []
    bob_prediction_Y = []

    eve_feature_rows = []
    eve_had_current_packet = []

    for t in range(T):
        true_index = state_history[t]
        true_state = states[true_index]
        true_y, true_s = true_state

        sent_packet = sender.transmit(true_state)

        bob_received = bob_channel.observe(sent_packet)
        eve_received = eve_channel.observe(sent_packet)

        # Bob
        bob_y, bob_s = bob_decoder.observe(bob_received)

        bob_prediction_Y.append(bob_y)
        bob_prediction_S.append(bob_s)

        # Eve
        features = eve_decoder.observe(eve_received)
        # Freeze this slot's features before exposing ACK_t or updating history.
        eve_feature_rows.append(features)
        eve_decoder.update(eve_received, bob_received is not None)

        eve_had_current_packet.append(eve_received is not None)

        progress = (t + 1) / T * 100
        if not options.quiet:
            print(f"\rProgress: {progress:.1f}%", end="", flush=True)

    print()

    # Eve is passive: predict all frozen feature rows in one batch.
    eve_S = eve_decoder.predict(np.asarray(eve_feature_rows))
    print(f"Simulation time: {time.perf_counter() - start:.1f} s")

    # Results:

    bob_Y = np.array(bob_prediction_Y)
    bob_S = np.array(bob_prediction_S)
    eve_had_current_packet = np.asarray(eve_had_current_packet)

    true_states = states[state_history]
    true_Y = true_states[:, 0]
    true_S = true_states[:, 1]

    bob_correct = (bob_Y == true_Y) & (bob_S == true_S)
    eve_wrong = eve_S != true_S

    CRA = bob_correct & eve_wrong

    print(f"Bob Y accuracy: {np.mean(bob_Y == true_Y):.1%}")
    print(f"Bob S accuracy: {np.mean(bob_S == true_S):.1%}")
    print(f"Bob joint (Y + S) accuracy: {np.mean(bob_correct):.1%}")
    print(f"Eve S accuracy: {np.mean(eve_S == true_S):.1%}")
    print(f"Average CRA: {np.mean(CRA):.1%}")

    # ~ is invert function. Basically, look at where Eve had no packet; 
    # What was her accuracy then (so when the RF-model actually did some work)
    hidden_mask = ~eve_had_current_packet
    if np.any(hidden_mask):
        print(f"Eve S accuracy when current packet unavailable: {np.mean(eve_S[hidden_mask] == true_S[hidden_mask]):.1%}")

if __name__ == "__main__":
    """
    Can run all different powers, or just choose one jam-power and run that.
    """
    jam_power = JAM_POWERS[1]
    run(jam_power)